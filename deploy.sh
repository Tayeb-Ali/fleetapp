#!/usr/bin/env bash
#
# Production deploy for bare-metal nginx + PHP-FPM servers.
#
# Usage (on the server, after updating the code):
#   cd /path/to/fleetapp && ./deploy.sh
#
# Build output (public/build) is git-ignored, so it MUST be produced here.
# Without this step Laravel cannot find the Vite manifest and the UI breaks.

set -euo pipefail

cd "$(dirname "$0")"

cyan=$'\033[36m'; green=$'\033[32m'; red=$'\033[31m'; yellow=$'\033[33m'; reset=$'\033[0m'
step() { printf '%s==> %s%s\n' "$cyan" "$1" "$reset"; }
ok()   { printf '%s    %s%s\n' "$green" "$1" "$reset"; }
warn() { printf '%s    %s%s\n' "$yellow" "$1" "$reset"; }
fail() { printf '%sERROR: %s%s\n' "$red" "$1" "$reset" >&2; exit 1; }

step "Checking toolchain"

command -v php      >/dev/null 2>&1 || fail "php is not in PATH"
command -v node     >/dev/null 2>&1 || fail "node is not in PATH (Vite 8 needs Node ^20.19 or >=22.12)"
command -v npm      >/dev/null 2>&1 || fail "npm is not in PATH"

has_composer=1
command -v composer >/dev/null 2>&1 || has_composer=0

node -e 'const [maj, min] = process.versions.node.split(".").map(Number); const ok = (maj === 20 && min >= 19) || (maj === 22 && min >= 12) || maj > 22; if (!ok) { console.error("Node " + process.versions.node + " is too old for Vite 8"); process.exit(1); }' \
    || fail "Upgrade Node on the server to 24.x (recommended) or 22.12+"

ok "php $(php -r 'echo PHP_VERSION;') / node $(node -v) / npm $(npm -v)"

[ -f artisan ] || fail "artisan not found — run this script from the project root"
[ -f .env ]    || fail ".env is missing — copy .env.example to .env and set APP_KEY, APP_URL, DB_*"

step "Removing stale Vite dev-server marker"
# public/hot redirects asset URLs to http://localhost:5173 and breaks production.
rm -f public/hot
ok "public/hot removed"

step "Installing PHP dependencies"
if [ "$has_composer" = "1" ]; then
    composer install --no-dev --optimize-autoloader --no-interaction
    ok "PHP dependencies installed"
elif [ -f vendor/autoload.php ]; then
    warn "composer not found — keeping the existing vendor/ directory"
else
    fail "composer is not in PATH and vendor/ is missing"
fi

step "Publishing Livewire assets"
# Served as real files from public/, so nginx static rules never 404 on the
# dynamic /livewire-<hash>/... route.
php artisan vendor:publish --tag=livewire:assets --force
ok "Livewire assets published to public/vendor/livewire"

step "Installing JS dependencies from package-lock.json"
npm ci --include=dev --no-audit --no-fund
[ -f node_modules/vite/bin/vite.js ] || fail "vite was not installed — check the npm ci output above"
ok "JS dependencies installed"

step "Building frontend assets"
npm run build
ok "Vite build finished"

[ -f public/build/manifest.json ] || fail "public/build/manifest.json was not generated by the build"
ok "manifest.json present"

step "Running database migrations"
php artisan migrate --force --no-interaction
ok "Migrations applied"

step "Rebuilding Laravel caches"
php artisan optimize:clear
php artisan optimize
ok "Caches rebuilt"

step "Fixing storage permissions"
chmod -R ug+rwX storage bootstrap/cache
ok "storage/ and bootstrap/cache/ are writable"

step "Verifying built assets are reachable over HTTP"
app_url="$(grep -E '^[[:space:]]*APP_URL=' .env | tail -n1 | cut -d= -f2- | tr -d "\"'" | xargs || true)"
case "$app_url" in
    http://*|https://*) ;;
    "") ;;
    *) app_url="https://$app_url" ;;
esac

if [ -z "$app_url" ]; then
    warn "APP_URL is not set in .env — skipping HTTP check"
elif ! command -v curl >/dev/null 2>&1; then
    warn "curl is not installed — skipping HTTP check"
else
    code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 "$app_url/build/manifest.json" || true)"
    if [ "$code" = "200" ]; then
        ok "$app_url/build/manifest.json -> 200"
    else
        warn "$app_url/build/manifest.json -> ${code:-no response}"
        warn "Check that nginx 'root' points to the project's public/ directory"
        warn "and that static files fall back to index.php (try_files \$uri /index.php?\$query_string;)."
    fi
fi

printf '\n%sDeploy finished.%s\n' "$green" "$reset"
